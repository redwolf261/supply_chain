"""Markdown tables of the multi-day results (experiments/results/multiday/*.csv), for the documentation.
Every cell is computed from the CSV files; nothing is typed in.

Usage:  python experiments/scripts/tables_multiday.py [results_dir]   -> writes <results_dir>/tables.md
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze import paired  # noqa: E402

RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "results" / "multiday"
SETTINGS = [("M1", "failed suppliers"), ("M2", "failed routes"), ("M3", "multiple"), ("M4", "capacity factor"), ("M5", "transit days"),
            ("M6", "demand noise"), ("M7", "penalty scale"), ("M10", "forecast (0 persistence, 1 perfect)")]
OTHERS = ["none", "bottleneck_aware", "bottleneck_aware_lambda0", "lookahead", "rolling_exact"]
SHORT = {"none": "none", "greedy": "greedy", "bottleneck_aware": "BA", "bottleneck_aware_lambda0": "BA λ=0", "lookahead": "look-ahead(5)",
         "rolling_exact": "rolling exact"}


def cell(n, m, h, lo, hi, eq):
    if m == 0 and h == 0:
        return "= (all equal)"
    value = f"{m:+,.0f} ± {h:,.0f}"
    return (f"**{value}**" if abs(m) > h else value) + f" ({lo}/{hi}/{eq})"


def table_paired():
    out = ["| Exp | x | " + " | ".join(f"{SHORT[o]} − greedy" for o in OTHERS) + " |", "|---|---|" + "---|" * len(OTHERS)]
    for exp, _ in SETTINGS:
        runs = pd.read_csv(RESULTS / f"{exp}_runs.csv")
        per = {o: {x: (n, m, h, lo, hi, eq) for x, n, m, h, lo, hi, eq in paired(runs, o, "greedy")} for o in OTHERS}
        for x in sorted(runs.x.unique()):
            out.append(f"| {exp} | {x:g} | " + " | ".join(cell(*per[o][x]) for o in OTHERS) + " |")
    return "\n".join(out)


def table_costs():
    labels = ["none", "greedy", "bottleneck_aware", "lookahead", "rolling_exact"]
    out = ["| Exp | x | " + " | ".join(SHORT[l] for l in labels) + " | bound runs |", "|---|---|" + "---|" * (len(labels) + 1)]
    for exp, _ in SETTINGS:
        s = pd.read_csv(RESULTS / f"{exp}_summary.csv")
        for x, g in s.groupby("x"):
            g = g.set_index("label")
            out.append(f"| {exp} | {x:g} | " + " | ".join(f"{g.loc[l, 'cost_mean'] / 1000:.1f}k ({g.loc[l, 'gap_to_bound_percent_mean']:.0f}%)" for l in labels)
                       + f" | {int(g['bound_runs'].iloc[0])}/{int(g['runs_completed'].iloc[0])} |")
    return "\n".join(out)


def table_recovery():
    labels = ["none", "greedy", "bottleneck_aware", "lookahead", "rolling_exact"]
    out = ["| Exp | x | " + " | ".join(SHORT[l] for l in labels) + " |", "|---|---|" + "---|" * len(labels)]
    for exp, _ in SETTINGS:
        s = pd.read_csv(RESULTS / f"{exp}_summary.csv")
        for x, g in s.groupby("x"):
            g = g.set_index("label")
            cells = []
            for l in labels:
                r, a = int(g.loc[l, "recovered_runs"]), int(g.loc[l, "recovery_applicable_runs"])
                days = g.loc[l, "recovery_days_mean"]
                cells.append(f"{r}/{a}" + (f", {days:.1f} d" if r > 0 else ""))
            out.append(f"| {exp} | {x:g} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def table_lookahead():
    s = pd.read_csv(RESULTS / "M8_summary.csv")
    runs = pd.read_csv(RESULTS / "M8_runs.csv")
    vs = {x: (n, m, h, lo, hi, eq) for x, n, m, h, lo, hi, eq in paired(runs, "lookahead", "greedy")}
    out = ["| look-ahead days | mean cost | look-ahead − greedy (95%) | decision time per run | greedy decision time |", "|---|---|---|---|---|"]
    for x, g in s.groupby("x"):
        g = g.set_index("label")
        out.append(f"| {x:g} | {g.loc['lookahead', 'cost_mean'] / 1000:.1f}k | {cell(*vs[x])} | {g.loc['lookahead', 'decision_ms_mean']:.1f} ms | {g.loc['greedy', 'decision_ms_mean']:.1f} ms |")
    return "\n".join(out)


def table_ablation():
    runs = pd.read_csv(RESULTS / "M9_runs.csv")
    out = ["| λ | BA(λ) − BA(λ=0), mean ± 95% | runs cheaper / dearer / equal | greedy − BA(λ=0) |", "|---|---|---|---|"]
    g0 = {x: (n, m, h, lo, hi, eq) for x, n, m, h, lo, hi, eq in paired(runs, "greedy", "bottleneck_aware_lambda0")}
    for x, n, m, h, lo, hi, eq in paired(runs, "bottleneck_aware", "bottleneck_aware_lambda0"):
        out.append(f"| {x:g} | {m:+.0f} ± {h:.0f} | {lo} / {hi} / {eq} | {cell(*g0[x])} |")
    return "\n".join(out)


def main():
    text = ["<!-- generated by experiments/scripts/tables_multiday.py from the CSV files; do not edit by hand -->",
            "\n### Paired cost difference to greedy\n",
            "Mean of cost(policy) − cost(greedy) over the same 20 scenarios, ± the 95% half-width, then (runs cheaper / dearer / equal). "
            "**Bold**: the 95% interval excludes 0 (negative = cheaper than greedy); otherwise the interval includes 0; = identical in every run.\n",
            table_paired(),
            "\n### Mean total cost (and mean % above the clairvoyant lower bound)\n", table_costs(),
            "\n### Recovered runs / runs, and mean recovery time of the recovered runs\n", table_recovery(),
            "\n### Look-ahead horizon (M8, scenario of M1 with 2 failed suppliers)\n", table_lookahead(),
            "\n### Ablation of the risk term (M9, multiple disruptions, 40 seeds)\n", table_ablation(), ""]
    (RESULTS / "tables.md").write_text("\n".join(text), encoding="utf-8")
    print(f"tables written to {RESULTS / 'tables.md'}")


if __name__ == "__main__":
    main()
